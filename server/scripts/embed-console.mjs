// Embeds the console kit's stylesheet and the scripts into the Worker as strings, so the server ships as
// one file on Cloudflare and in Docker alike. Writes src/console/bundle.ts (not committed).
import { readFile, writeFile } from 'node:fs/promises'

const dir = new URL('../src/console/', import.meta.url)
const read = (name) => readFile(new URL(name, dir), 'utf8')
const [js, kitCss, kitJs, icons] = await Promise.all([read('console.js'), read('kit.css'), read('kit.js'), read('icons.js')])
await writeFile(
  new URL('bundle.ts', dir),
  `// Generated by scripts/embed-console.mjs. Do not edit.\nexport const CONSOLE_JS = ${JSON.stringify(js)}\nexport const KIT_CSS = ${JSON.stringify(kitCss)}\nexport const KIT_JS = ${JSON.stringify(kitJs)}\nexport const ICONS_JS = ${JSON.stringify(icons)}\n`
)
console.log('[kalka] Console embedded')
